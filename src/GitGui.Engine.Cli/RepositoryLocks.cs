using System.Diagnostics;
using System.Text;
using GitGui.Core;

namespace GitGui.Engine.Cli;

internal sealed class RepositoryIndexLock : IAsyncDisposable
{
    private readonly string index;
    private readonly string path;
    private FileStream? handle;
    private bool owned = true;
    private RepositoryIndexLock(string index)
    {
        this.index = index;
        path = index + ".lock";
        try { handle = new(path, FileMode.CreateNew, FileAccess.ReadWrite, FileShare.None); }
        catch (IOException) { throw new InvalidOperationException("index.lock exists. Wait for other Git operations to finish; no lock was removed."); }
    }
    public static async Task<RepositoryIndexLock> Acquire(GitAccess git, string root, CancellationToken ct)
        => new(await git.Text(root, ct, "rev-parse", "--path-format=absolute", "--git-path", "index"));

    // The complete index is generated by Git in an alternate index, never edited by this application.
    public async Task Install(string generated, CancellationToken ct)
    {
        handle!.SetLength(0);
        await using (var source = File.OpenRead(generated)) await source.CopyToAsync(handle, ct);
        await handle.FlushAsync(ct);
        handle.Flush(flushToDisk: true);
        await handle.DisposeAsync(); handle = null;
        File.Move(path, index, true);
        owned = false;
    }
    public async ValueTask DisposeAsync()
    {
        if (handle is not null) await handle.DisposeAsync();
        if (owned) File.Delete(path);
    }
}

internal sealed class PreparedRefs : IAsyncDisposable
{
    private readonly Process process;
    private readonly Task<string> errors;
    private readonly string commands;
    private readonly GitProcessRunner runner;
    private readonly Stopwatch watch = Stopwatch.StartNew();
    private bool completed;
    private PreparedRefs(Process process, string commands, GitProcessRunner runner)
    { this.process = process; this.commands = commands; this.runner = runner; errors = process.StandardError.ReadToEndAsync(); }

    public static async Task<PreparedRefs> Begin(string root, string commands, GitProcessRunner runner, CancellationToken ct)
    {
        var start = await runner.CreateStartInfoAsync(root, ct);
        foreach (var arg in new[] { "-c", "core.fsmonitor=false", "update-ref", "--stdin" }) start.ArgumentList.Add(arg);
        start.Environment["LC_ALL"] = "C";
        start.Environment["GIT_TERMINAL_PROMPT"] = "0";
        foreach (var key in start.Environment.Keys.Where(k => k.StartsWith("GIT_TRACE", StringComparison.Ordinal)).ToArray()) start.Environment.Remove(key);
        var process = Process.Start(start)!;
        var transaction = new PreparedRefs(process, commands, runner);
        using var cancellation = ct.Register(() =>
        {
            try { if (!process.HasExited) process.Kill(entireProcessTree: true); }
            catch (InvalidOperationException) { }
        });
        try
        {
            await process.StandardInput.WriteAsync(("start\n" + commands + "prepare\n").AsMemory(), ct);
            await process.StandardInput.FlushAsync(ct);
            if (await process.StandardOutput.ReadLineAsync(ct) != "start: ok" ||
                await process.StandardOutput.ReadLineAsync(ct) != "prepare: ok")
            {
                process.StandardInput.Close();
                await process.WaitForExitAsync(ct);
                ct.ThrowIfCancellationRequested();
                throw new InvalidOperationException("Cannot prepare atomic ref restoration: " + GitProcessRunner.Redact(await transaction.errors));
            }
            return transaction;
        }
        catch { await transaction.DisposeAsync(); throw; }
    }

    public async Task Commit()
    {
        await process.StandardInput.WriteAsync("commit\n");
        await process.StandardInput.FlushAsync();
        var response = await process.StandardOutput.ReadLineAsync();
        process.StandardInput.Close();
        await process.WaitForExitAsync();
        var error = GitProcessRunner.Redact(await errors);
        completed = true;
        runner.Record(new(DateTimeOffset.Now, GitProcessRunner.FormatCommand(process.StartInfo.FileName, ["update-ref", "--stdin"]),
            commands + "prepare\ncommit\n" + error, process.ExitCode, watch.Elapsed));
        if (response != "commit: ok" || process.ExitCode != 0) throw new InvalidOperationException("Ref restoration failed: " + error);
    }
    public async ValueTask DisposeAsync()
    {
        if (!completed && !process.HasExited)
        {
            try { await process.StandardInput.WriteAsync("abort\n"); process.StandardInput.Close(); }
            catch (IOException) { }
            try { await process.WaitForExitAsync().WaitAsync(TimeSpan.FromSeconds(5)); }
            catch (TimeoutException) { process.Kill(entireProcessTree: true); await process.WaitForExitAsync(); }
        }
        process.Dispose();
    }
}
